import React, { useState } from 'react';
import { MOCK_ICEBERG_DDL, MOCK_DELTA_DDL, MOCK_EVENTS } from '../mockData';

interface ExportPageProps {
  onNavigate: (path: string) => void;
  onShowToast: (message: string, type?: 'success' | 'info' | 'error') => void;
}

export const ExportPage: React.FC<ExportPageProps> = ({ onShowToast }) => {
  const [selectedEventId, setSelectedEventId] = useState('orders.order.completed');
  const [engineFormat, setEngineFormat] = useState<'iceberg' | 'delta'>('iceberg');
  const [targetLang, setTargetLang] = useState<'typescript' | 'python' | 'go'>('typescript');

  const selectedEvent = MOCK_EVENTS.find((e) => e.id === selectedEventId) || MOCK_EVENTS[0];

  const copyToClipboard = (text: string, label: string) => {
    navigator.clipboard?.writeText(text);
    onShowToast(`Copied ${label} to clipboard`, 'success');
  };

  const getCLICommand = () => {
    return `kalyxctl generate --event ${selectedEvent.type} --lang ${targetLang} --out ./src/events`;
  };

  const getCodeSnippet = () => {
    if (targetLang === 'typescript') {
      return `// Generated by Kalyx CLI (kalyxctl) v1.0.0
// Contract: ${selectedEvent.type} (v1.2.0)
import { CloudEvent } from 'cloudevents';

export interface OrderCompletedData {
  order_id: string;
  customer_id: string;
  customer_email: string;
  amount_cents: number;
  currency: 'USD' | 'EUR' | 'GBP';
  completed_at: string;
}

export function createOrderCompletedEvent(
  source: string,
  data: OrderCompletedData
): CloudEvent<OrderCompletedData> {
  return new CloudEvent({
    specversion: '1.0',
    type: '${selectedEvent.type}',
    source,
    id: crypto.randomUUID(),
    time: new Date().toISOString(),
    datacontenttype: 'application/json',
    data,
  });
}`;
    }

    if (targetLang === 'python') {
      return `# Generated by Kalyx CLI (kalyxctl) v1.0.0
# Contract: ${selectedEvent.type} (v1.2.0)
from dataclasses import dataclass
from datetime import datetime
from cloudevents.http import CloudEvent
import uuid

@dataclass
class OrderCompletedData:
    order_id: str
    customer_id: str
    customer_email: str
    amount_cents: int
    currency: str
    completed_at: str

def create_order_completed_event(source: str, data: OrderCompletedData) -> CloudEvent:
    attributes = {
        "type": "${selectedEvent.type}",
        "source": source,
        "id": str(uuid.uuid4()),
        "time": datetime.utcnow().isoformat(),
        "datacontenttype": "application/json"
    }
    return CloudEvent(attributes, data.__dict__)`;
    }

    return `// Generated by Kalyx CLI (kalyxctl) v1.0.0
// Contract: ${selectedEvent.type} (v1.2.0)
package events

import (
	"time"
	cloudevents "github.com/cloudevents/sdk-go/v2"
	"github.com/google/uuid"
)

type OrderCompletedData struct {
	OrderID       string \`json:"order_id"\`
	CustomerID    string \`json:"customer_id"\`
	CustomerEmail string \`json:"customer_email"\`
	AmountCents   int64  \`json:"amount_cents"\`
	Currency      string \`json:"currency"\`
	CompletedAt   string \`json:"completed_at"\`
}

func NewOrderCompletedEvent(source string, data OrderCompletedData) cloudevents.Event {
	event := cloudevents.NewEvent()
	event.SetID(uuid.New().String())
	event.SetSource(source)
	event.SetType("${selectedEvent.type}")
	event.SetTime(time.Now().UTC())
	_ = event.SetData(cloudevents.ApplicationJSON, data)
	return event
}`;
  };

  return (
    <div className="flex flex-col w-full pb-16">
      <div className="px-space-lg py-space-md flex flex-col gap-space-lg max-w-[1720px] mx-auto w-full">
        {/* Header */}
        <div className="flex flex-wrap items-center justify-between gap-space-md border-b border-outline-variant/40 pb-4">
          <div className="flex flex-col gap-0.5">
            <div className="flex items-center gap-2 font-label-sm text-label-sm">
              <span className="text-primary uppercase tracking-wider">Export Center</span>
              <span className="text-outline-variant">/</span>
              <span className="text-on-surface-variant">DDL &amp; SDK Automation</span>
            </div>
            <h1 className="font-headline-lg text-headline-lg text-on-surface font-semibold tracking-tight">
              Export Center &amp; SDK Generator
            </h1>
          </div>

          {/* Event Contract Selector */}
          <div className="flex items-center gap-2">
            <span className="font-label-sm text-label-sm text-outline">Target Contract:</span>
            <select
              value={selectedEventId}
              onChange={(e) => setSelectedEventId(e.target.value)}
              className="h-8 px-3 rounded bg-surface-container-low border border-outline-variant text-on-surface font-body-sm text-body-sm focus:outline-none focus:border-primary cursor-pointer"
            >
              {MOCK_EVENTS.map((e) => (
                <option key={e.id} value={e.id}>
                  {e.name} ({e.domain})
                </option>
              ))}
            </select>
          </div>
        </div>

        {/* 1. DATA LAKE DDL GENERATOR */}
        <div className="p-5 rounded-DEFAULT border border-outline-variant bg-surface-container-low flex flex-col gap-4">
          <div className="flex items-center justify-between border-b border-outline-variant/60 pb-3">
            <div className="flex items-center gap-2">
              <span className="material-symbols-outlined text-primary text-[20px]">
                table_chart_view
              </span>
              <div>
                <h2 className="font-headline-md text-headline-md text-on-surface font-semibold">
                  Data Lake DDL Generator
                </h2>
                <p className="text-body-sm text-outline">
                  Automate table creation in modern lakehouses synchronized with CloudEvents schemas.
                </p>
              </div>
            </div>

            <div className="flex items-center gap-2">
              <div className="inline-flex rounded bg-surface-container-lowest p-0.5 border border-outline-variant">
                <button
                  onClick={() => setEngineFormat('iceberg')}
                  className={`px-3 py-1 rounded font-label-sm text-label-sm font-semibold transition-colors ${
                    engineFormat === 'iceberg'
                      ? 'bg-primary-container text-on-primary'
                      : 'text-outline hover:text-on-surface'
                  }`}
                >
                  Apache Iceberg (SQL)
                </button>
                <button
                  onClick={() => setEngineFormat('delta')}
                  className={`px-3 py-1 rounded font-label-sm text-label-sm font-semibold transition-colors ${
                    engineFormat === 'delta'
                      ? 'bg-primary-container text-on-primary'
                      : 'text-outline hover:text-on-surface'
                  }`}
                >
                  Delta Lake 3.0 (SQL)
                </button>
              </div>

              <button
                onClick={() =>
                  copyToClipboard(
                    engineFormat === 'iceberg' ? MOCK_ICEBERG_DDL : MOCK_DELTA_DDL,
                    `${engineFormat.toUpperCase()} DDL`
                  )
                }
                className="h-8 px-3 rounded bg-surface-container hover:bg-surface-container-high border border-outline-variant text-on-surface font-label-sm text-label-sm inline-flex items-center gap-1.5 transition-colors"
              >
                <span className="material-symbols-outlined text-[14px]">content_copy</span>
                <span>Copy SQL DDL</span>
              </button>
            </div>
          </div>

          <div className="p-4 rounded bg-[#0a0e16] border border-outline-variant font-mono text-[12px] leading-relaxed text-[#dfe2ee] overflow-x-auto shadow-inner">
            <pre>{engineFormat === 'iceberg' ? MOCK_ICEBERG_DDL : MOCK_DELTA_DDL}</pre>
          </div>
        </div>

        {/* 2. MICROSERVICE SDK GENERATOR (kalyxctl) */}
        <div className="p-5 rounded-DEFAULT border border-outline-variant bg-surface-container-low flex flex-col gap-4">
          <div className="flex items-center justify-between border-b border-outline-variant/60 pb-3">
            <div className="flex items-center gap-2">
              <span className="material-symbols-outlined text-tertiary text-[20px]">terminal</span>
              <div>
                <h2 className="font-headline-md text-headline-md text-on-surface font-semibold">
                  Microservice SDK Generator (<code className="text-primary font-mono">kalyxctl</code>)
                </h2>
                <p className="text-body-sm text-outline">
                  Generate strongly-typed CloudEvent models and builders for microservices.
                </p>
              </div>
            </div>

            <div className="flex items-center gap-2">
              <div className="inline-flex rounded bg-surface-container-lowest p-0.5 border border-outline-variant">
                {(['typescript', 'python', 'go'] as const).map((lang) => (
                  <button
                    key={lang}
                    onClick={() => setTargetLang(lang)}
                    className={`px-3 py-1 rounded font-label-sm text-label-sm font-semibold capitalize transition-colors ${
                      targetLang === lang
                        ? 'bg-tertiary-container text-on-tertiary'
                        : 'text-outline hover:text-on-surface'
                    }`}
                  >
                    {lang}
                  </button>
                ))}
              </div>
            </div>
          </div>

          {/* CLI One-Liner Box */}
          <div className="flex flex-col gap-1.5">
            <span className="font-label-sm text-label-sm text-outline uppercase tracking-wider">
              1-Click Terminal Command
            </span>
            <div className="flex items-center justify-between p-3 rounded bg-[#070a0f] border border-outline-variant/80 font-mono text-body-sm text-primary">
              <div className="flex items-center gap-2 truncate">
                <span className="text-tertiary font-bold">$</span>
                <span className="truncate">{getCLICommand()}</span>
              </div>
              <button
                onClick={() => copyToClipboard(getCLICommand(), 'CLI command')}
                className="ml-3 px-2.5 py-1 rounded bg-surface-container hover:bg-surface-container-high border border-outline-variant text-on-surface text-xs font-label-sm inline-flex items-center gap-1 shrink-0 transition-colors"
              >
                <span className="material-symbols-outlined text-[13px]">content_copy</span>
                <span>Copy</span>
              </button>
            </div>
          </div>

          {/* Generated Code Preview */}
          <div className="flex flex-col gap-1.5 mt-2">
            <div className="flex items-center justify-between">
              <span className="font-label-sm text-label-sm text-outline uppercase tracking-wider">
                Generated Model Preview ({targetLang})
              </span>
              <button
                onClick={() => copyToClipboard(getCodeSnippet(), `${targetLang} code`)}
                className="text-xs text-primary hover:underline font-label-sm flex items-center gap-1"
              >
                <span className="material-symbols-outlined text-[13px]">content_copy</span>
                <span>Copy Source Code</span>
              </button>
            </div>
            <div className="p-4 rounded bg-[#0a0e16] border border-outline-variant font-mono text-[12px] leading-relaxed text-[#dfe2ee] overflow-x-auto shadow-inner">
              <pre>{getCodeSnippet()}</pre>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};
