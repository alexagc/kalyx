package codegen

import (
	"encoding/json"
	"fmt"
	"strings"
)

// GenerateTypeScript produces strongly-typed TypeScript interfaces, a JSON Schema runtime validator,
// and a CloudEvent v1.0.2 builder function create<EventName>CloudEvent(...).
func GenerateTypeScript(contract EventContract) (string, error) {
	eventName := DeriveEventName(contract.Name, contract.Type)
	payloadInterface := eventName + "Payload"
	cloudEventInterface := eventName + "CloudEvent"
	builderName := "create" + eventName + "CloudEvent"
	validatorPayloadName := "validate" + eventName + "Payload"
	validatorCloudEventName := "validate" + eventName + "CloudEvent"
	optionsInterface := "Create" + eventName + "Options"
	schemaConstName := ToCamelCase(eventName) + "JSONSchema"

	var sb strings.Builder
	sb.WriteString("// Code generated by kalyxctl. DO NOT EDIT.\n")
	sb.WriteString(fmt.Sprintf("// Event: %s (Type: %s, Version: %s)\n", eventName, contract.Type, contract.SemVer))
	if contract.Description != "" {
		sb.WriteString(fmt.Sprintf("// Description: %s\n", contract.Description))
	}
	if contract.Deprecated {
		sb.WriteString(fmt.Sprintf("// @deprecated RFC 8594: This contract version is deprecated. Sunset: %s\n", contract.SunsetDate))
	}
	sb.WriteString("\n")

	// Payload interface
	sb.WriteString("/**\n")
	sb.WriteString(fmt.Sprintf(" * Typed payload for %s.\n", eventName))
	if contract.Description != "" {
		sb.WriteString(fmt.Sprintf(" * %s\n", contract.Description))
	}
	sb.WriteString(" */\n")
	sb.WriteString(fmt.Sprintf("export interface %s {\n", payloadInterface))

	for _, prop := range contract.Schema.Properties {
		if prop.Description != "" {
			sb.WriteString(fmt.Sprintf("  /** %s */\n", prop.Description))
		}
		opt := ""
		if !prop.Required {
			opt = "?"
		}
		tsType := mapToTSType(prop.Type, prop.ItemType)
		sb.WriteString(fmt.Sprintf("  %s%s: %s;\n", prop.Name, opt, tsType))
	}
	sb.WriteString("}\n\n")

	// CloudEvent v1.0.2 interface
	sb.WriteString("/**\n")
	sb.WriteString(fmt.Sprintf(" * CNCF CloudEvent v1.0.2 representation for %s.\n", eventName))
	sb.WriteString(" */\n")
	sb.WriteString(fmt.Sprintf("export interface %s {\n", cloudEventInterface))
	sb.WriteString("  specversion: \"1.0\";\n")
	sb.WriteString("  id: string;\n")
	sb.WriteString("  source: string;\n")
	sb.WriteString(fmt.Sprintf("  type: %q;\n", contract.Type))
	sb.WriteString("  time?: string;\n")
	sb.WriteString("  datacontenttype?: \"application/json\";\n")
	sb.WriteString("  dataschema?: string;\n")
	sb.WriteString("  subject?: string;\n")
	sb.WriteString(fmt.Sprintf("  data: %s;\n", payloadInterface))
	sb.WriteString("}\n\n")

	// Raw JSON Schema constant
	schemaJSON, err := json.MarshalIndent(contract.Schema, "", "  ")
	if err == nil && len(schemaJSON) > 0 {
		sb.WriteString("/**\n * Embedded JSON Schema Draft 2020-12 definition.\n */\n")
		sb.WriteString(fmt.Sprintf("export const %s = %s as const;\n\n", schemaConstName, string(schemaJSON)))
	}

	// Runtime validator for Payload
	sb.WriteString("/**\n")
	sb.WriteString(fmt.Sprintf(" * Runtime validator for %s.\n", payloadInterface))
	sb.WriteString(" */\n")
	sb.WriteString(fmt.Sprintf("export function %s(data: unknown): data is %s {\n", validatorPayloadName, payloadInterface))
	sb.WriteString("  if (typeof data !== \"object\" || data === null) {\n")
	sb.WriteString("    return false;\n")
	sb.WriteString("  }\n")
	sb.WriteString("  const candidate = data as Record<string, unknown>;\n\n")

	for _, prop := range contract.Schema.Properties {
		if prop.Required {
			sb.WriteString(fmt.Sprintf("  if (!(%q in candidate)) return false;\n", prop.Name))
			tsCheck := mapTSTypeCheck("candidate["+fmt.Sprintf("%q", prop.Name)+"]", prop.Type)
			if tsCheck != "" {
				sb.WriteString(fmt.Sprintf("  if (!%s) return false;\n", tsCheck))
			}
		} else {
			tsCheck := mapTSTypeCheck("candidate["+fmt.Sprintf("%q", prop.Name)+"]", prop.Type)
			if tsCheck != "" {
				sb.WriteString(fmt.Sprintf("  if (%q in candidate && candidate[%q] !== undefined && candidate[%q] !== null && !%s) return false;\n", prop.Name, prop.Name, prop.Name, tsCheck))
			}
		}
	}
	sb.WriteString("  return true;\n")
	sb.WriteString("}\n\n")

	// Runtime validator for CloudEvent
	sb.WriteString("/**\n")
	sb.WriteString(fmt.Sprintf(" * Runtime validator for %s.\n", cloudEventInterface))
	sb.WriteString(" */\n")
	sb.WriteString(fmt.Sprintf("export function %s(event: unknown): event is %s {\n", validatorCloudEventName, cloudEventInterface))
	sb.WriteString("  if (typeof event !== \"object\" || event === null) {\n")
	sb.WriteString("    return false;\n")
	sb.WriteString("  }\n")
	sb.WriteString("  const ce = event as Record<string, unknown>;\n")
	sb.WriteString("  if (ce.specversion !== \"1.0\") return false;\n")
	sb.WriteString("  if (typeof ce.id !== \"string\" || ce.id.length === 0) return false;\n")
	sb.WriteString("  if (typeof ce.source !== \"string\" || ce.source.length === 0) return false;\n")
	sb.WriteString(fmt.Sprintf("  if (ce.type !== %q) return false;\n", contract.Type))
	sb.WriteString(fmt.Sprintf("  return %s(ce.data);\n", validatorPayloadName))
	sb.WriteString("}\n\n")

	// CloudEvent Options
	sb.WriteString(fmt.Sprintf("export interface %s {\n", optionsInterface))
	sb.WriteString("  id?: string;\n")
	sb.WriteString("  time?: string;\n")
	sb.WriteString("  subject?: string;\n")
	sb.WriteString("  dataschema?: string;\n")
	sb.WriteString("}\n\n")

	// CloudEvent Builder Function
	sb.WriteString("/**\n")
	sb.WriteString(fmt.Sprintf(" * Builds a CNCF CloudEvent v1.0.2 for %s.\n", eventName))
	sb.WriteString(" */\n")
	sb.WriteString(fmt.Sprintf("export function %s(\n", builderName))
	sb.WriteString(fmt.Sprintf("  data: %s,\n", payloadInterface))
	sb.WriteString("  source: string,\n")
	sb.WriteString(fmt.Sprintf("  options?: %s\n", optionsInterface))
	sb.WriteString(fmt.Sprintf("): %s {\n", cloudEventInterface))
	sb.WriteString("  const eventId = options?.id ?? (\n")
	sb.WriteString("    typeof crypto !== \"undefined\" && typeof crypto.randomUUID === \"function\"\n")
	sb.WriteString("      ? crypto.randomUUID()\n")
	sb.WriteString("      : \"ce-\" + Date.now().toString(36) + \"-\" + Math.random().toString(36).substring(2, 9)\n")
	sb.WriteString("  );\n\n")
	sb.WriteString("  return {\n")
	sb.WriteString("    specversion: \"1.0\",\n")
	sb.WriteString("    id: eventId,\n")
	sb.WriteString("    source,\n")
	sb.WriteString(fmt.Sprintf("    type: %q,\n", contract.Type))
	sb.WriteString("    time: options?.time ?? new Date().toISOString(),\n")
	sb.WriteString("    datacontenttype: \"application/json\",\n")
	sb.WriteString("    dataschema: options?.dataschema,\n")
	sb.WriteString("    subject: options?.subject,\n")
	sb.WriteString("    data,\n")
	sb.WriteString("  };\n")
	sb.WriteString("}\n")

	return sb.String(), nil
}

func mapToTSType(schemaType, itemType string) string {
	switch schemaType {
	case "string":
		return "string"
	case "number", "integer":
		return "number"
	case "boolean":
		return "boolean"
	case "array":
		if itemType != "" && itemType != "any" {
			return mapToTSType(itemType, "") + "[]"
		}
		return "unknown[]"
	case "object":
		return "Record<string, unknown>"
	default:
		return "unknown"
	}
}

func mapTSTypeCheck(accessor, schemaType string) string {
	switch schemaType {
	case "string":
		return fmt.Sprintf("typeof %s === \"string\"", accessor)
	case "number", "integer":
		return fmt.Sprintf("typeof %s === \"number\" && !isNaN(%s)", accessor, accessor)
	case "boolean":
		return fmt.Sprintf("typeof %s === \"boolean\"", accessor)
	case "array":
		return fmt.Sprintf("Array.isArray(%s)", accessor)
	case "object":
		return fmt.Sprintf("typeof %s === \"object\" && %s !== null", accessor, accessor)
	default:
		return ""
	}
}
