package codegen

import (
	"fmt"
	"strings"
)

// GeneratePython produces Pydantic v2 BaseModel classes with type annotations
// and a CloudEvent helper function for Python clients.
func GeneratePython(contract EventContract) (string, error) {
	eventName := DeriveEventName(contract.Name, contract.Type)
	payloadClass := eventName + "Payload"
	cloudEventClass := eventName + "CloudEvent"
	snakeName := ToSnakeCase(eventName)
	helperName := "create_" + snakeName + "_cloud_event"

	var sb strings.Builder
	sb.WriteString("# Code generated by kalyxctl. DO NOT EDIT.\n")
	sb.WriteString(fmt.Sprintf("# Event: %s (Type: %s, Version: %s)\n", eventName, contract.Type, contract.SemVer))
	if contract.Description != "" {
		sb.WriteString(fmt.Sprintf("# Description: %s\n", contract.Description))
	}
	if contract.Deprecated {
		sb.WriteString(fmt.Sprintf("# WARNING: Contract is deprecated per RFC 8594. Sunset date: %s\n", contract.SunsetDate))
	}
	sb.WriteString("\n")

	sb.WriteString("from __future__ import annotations\n")
	sb.WriteString("from typing import Optional, List, Dict, Any\n")
	sb.WriteString("from datetime import datetime, timezone\n")
	sb.WriteString("import uuid\n")
	sb.WriteString("from pydantic import BaseModel, Field, ConfigDict\n\n")

	// Payload Model
	sb.WriteString(fmt.Sprintf("class %s(BaseModel):\n", payloadClass))
	sb.WriteString("    \"\"\"\n")
	sb.WriteString(fmt.Sprintf("    Typed payload for %s.\n", eventName))
	if contract.Description != "" {
		sb.WriteString(fmt.Sprintf("    %s\n", contract.Description))
	}
	sb.WriteString("    \"\"\"\n")
	sb.WriteString("    model_config = ConfigDict(populate_by_name=True, extra=\"ignore\")\n\n")

	if len(contract.Schema.Properties) == 0 {
		sb.WriteString("    pass\n\n")
	} else {
		for _, prop := range contract.Schema.Properties {
			pyType := mapToPythonType(prop.Type, prop.ItemType)
			desc := strings.ReplaceAll(prop.Description, `"`, `\"`)
			if prop.Required {
				if desc != "" {
					sb.WriteString(fmt.Sprintf("    %s: %s = Field(description=%q)\n", prop.Name, pyType, desc))
				} else {
					sb.WriteString(fmt.Sprintf("    %s: %s\n", prop.Name, pyType))
				}
			} else {
				if desc != "" {
					sb.WriteString(fmt.Sprintf("    %s: Optional[%s] = Field(default=None, description=%q)\n", prop.Name, pyType, desc))
				} else {
					sb.WriteString(fmt.Sprintf("    %s: Optional[%s] = Field(default=None)\n", prop.Name, pyType))
				}
			}
		}
		sb.WriteString("\n")
	}

	// CloudEvent Model
	sb.WriteString(fmt.Sprintf("class %s(BaseModel):\n", cloudEventClass))
	sb.WriteString("    \"\"\"\n")
	sb.WriteString(fmt.Sprintf("    CNCF CloudEvent v1.0.2 wrapper for %s.\n", eventName))
	sb.WriteString("    \"\"\"\n")
	sb.WriteString("    model_config = ConfigDict(populate_by_name=True)\n\n")
	sb.WriteString("    specversion: str = Field(default=\"1.0\")\n")
	sb.WriteString("    id: str = Field(default_factory=lambda: str(uuid.uuid4()))\n")
	sb.WriteString("    source: str\n")
	sb.WriteString(fmt.Sprintf("    type: str = Field(default=%q)\n", contract.Type))
	sb.WriteString("    time: Optional[str] = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())\n")
	sb.WriteString("    datacontenttype: Optional[str] = Field(default=\"application/json\")\n")
	sb.WriteString("    dataschema: Optional[str] = Field(default=None)\n")
	sb.WriteString("    subject: Optional[str] = Field(default=None)\n")
	sb.WriteString(fmt.Sprintf("    data: %s\n\n", payloadClass))

	// CloudEvent Helper Function
	sb.WriteString(fmt.Sprintf("def %s(\n", helperName))
	sb.WriteString(fmt.Sprintf("    data: %s,\n", payloadClass))
	sb.WriteString("    source: str,\n")
	sb.WriteString("    id: Optional[str] = None,\n")
	sb.WriteString("    time: Optional[str] = None,\n")
	sb.WriteString("    subject: Optional[str] = None,\n")
	sb.WriteString("    dataschema: Optional[str] = None,\n")
	sb.WriteString(fmt.Sprintf(") -> %s:\n", cloudEventClass))
	sb.WriteString(fmt.Sprintf("    \"\"\"Helper to construct a strongly-typed %s CloudEvent.\"\"\"\n", eventName))
	sb.WriteString(fmt.Sprintf("    return %s(\n", cloudEventClass))
	sb.WriteString("        id=id or str(uuid.uuid4()),\n")
	sb.WriteString("        source=source,\n")
	sb.WriteString(fmt.Sprintf("        type=%q,\n", contract.Type))
	sb.WriteString("        time=time or datetime.now(timezone.utc).isoformat(),\n")
	sb.WriteString("        datacontenttype=\"application/json\",\n")
	sb.WriteString("        dataschema=dataschema,\n")
	sb.WriteString("        subject=subject,\n")
	sb.WriteString("        data=data,\n")
	sb.WriteString("    )\n")

	return sb.String(), nil
}

func mapToPythonType(schemaType, itemType string) string {
	switch schemaType {
	case "string":
		return "str"
	case "number":
		return "float"
	case "integer":
		return "int"
	case "boolean":
		return "bool"
	case "array":
		if itemType != "" && itemType != "any" {
			return fmt.Sprintf("List[%s]", mapToPythonType(itemType, ""))
		}
		return "List[Any]"
	case "object":
		return "Dict[str, Any]"
	default:
		return "Any"
	}
}
