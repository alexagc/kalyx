package codegen

import (
	"fmt"
	"strings"
)

// GenerateGo produces strongly-typed Go structs with json tags and builder function.
func GenerateGo(contract EventContract, packageName string) (string, error) {
	if packageName == "" {
		packageName = "events"
	}

	eventName := DeriveEventName(contract.Name, contract.Type)
	payloadStruct := eventName + "Payload"
	cloudEventStruct := eventName + "CloudEvent"
	optionType := "Create" + eventName + "Option"
	builderName := "Create" + eventName + "CloudEvent"

	var sb strings.Builder
	sb.WriteString("// Code generated by kalyxctl. DO NOT EDIT.\n")
	sb.WriteString(fmt.Sprintf("// Event: %s (Type: %s, Version: %s)\n", eventName, contract.Type, contract.SemVer))
	if contract.Description != "" {
		sb.WriteString(fmt.Sprintf("// Description: %s\n", contract.Description))
	}
	if contract.Deprecated {
		sb.WriteString(fmt.Sprintf("// Deprecated: RFC 8594 sunset warning. Sunset date: %s\n", contract.SunsetDate))
	}
	sb.WriteString("\n")

	sb.WriteString(fmt.Sprintf("package %s\n\n", packageName))
	sb.WriteString("import (\n")
	sb.WriteString("\t\"fmt\"\n")
	sb.WriteString("\t\"time\"\n")
	sb.WriteString(")\n\n")

	// Payload struct
	sb.WriteString(fmt.Sprintf("// %s represents the payload data for %s.\n", payloadStruct, eventName))
	sb.WriteString(fmt.Sprintf("type %s struct {\n", payloadStruct))

	for _, prop := range contract.Schema.Properties {
		goFieldName := formatGoFieldName(prop.Name)
		goType := mapToGoType(prop.Type, prop.ItemType)
		jsonTag := prop.Name
		if !prop.Required {
			jsonTag += ",omitempty"
		}
		if prop.Description != "" {
			sb.WriteString(fmt.Sprintf("\t// %s: %s\n", goFieldName, prop.Description))
		}
		sb.WriteString(fmt.Sprintf("\t%s %s `json:%q`\n", goFieldName, goType, jsonTag))
	}
	sb.WriteString("}\n\n")

	// CloudEvent struct
	sb.WriteString(fmt.Sprintf("// %s represents the CloudEvent v1.0.2 envelope for %s.\n", cloudEventStruct, eventName))
	sb.WriteString(fmt.Sprintf("type %s struct {\n", cloudEventStruct))
	sb.WriteString("\tSpecVersion     string                 `json:\"specversion\"`\n")
	sb.WriteString("\tID              string                 `json:\"id\"`\n")
	sb.WriteString("\tSource          string                 `json:\"source\"`\n")
	sb.WriteString("\tType            string                 `json:\"type\"`\n")
	sb.WriteString("\tTime            string                 `json:\"time,omitempty\"`\n")
	sb.WriteString("\tDataContentType string                 `json:\"datacontenttype,omitempty\"`\n")
	sb.WriteString("\tDataSchema      string                 `json:\"dataschema,omitempty\"`\n")
	sb.WriteString("\tSubject         string                 `json:\"subject,omitempty\"`\n")
	sb.WriteString(fmt.Sprintf("\tData            %s `json:\"data\"`\n", payloadStruct))
	sb.WriteString("}\n\n")

	// Builder Functional Options
	sb.WriteString(fmt.Sprintf("// %s configures optional fields on %s.\n", optionType, cloudEventStruct))
	sb.WriteString(fmt.Sprintf("type %s func(*%s)\n\n", optionType, cloudEventStruct))

	sb.WriteString(fmt.Sprintf("// With%sID sets a custom CloudEvent ID.\n", eventName))
	sb.WriteString(fmt.Sprintf("func With%sID(id string) %s {\n", eventName, optionType))
	sb.WriteString(fmt.Sprintf("\treturn func(e *%s) {\n\t\te.ID = id\n\t}\n", cloudEventStruct))
	sb.WriteString("}\n\n")

	sb.WriteString(fmt.Sprintf("// With%sTime sets a custom timestamp.\n", eventName))
	sb.WriteString(fmt.Sprintf("func With%sTime(t time.Time) %s {\n", eventName, optionType))
	sb.WriteString(fmt.Sprintf("\treturn func(e *%s) {\n\t\te.Time = t.UTC().Format(time.RFC3339)\n\t}\n", cloudEventStruct))
	sb.WriteString("}\n\n")

	sb.WriteString(fmt.Sprintf("// With%sSubject sets the event subject.\n", eventName))
	sb.WriteString(fmt.Sprintf("func With%sSubject(subject string) %s {\n", eventName, optionType))
	sb.WriteString(fmt.Sprintf("\treturn func(e *%s) {\n\t\te.Subject = subject\n\t}\n", cloudEventStruct))
	sb.WriteString("}\n\n")

	// Builder Function
	sb.WriteString(fmt.Sprintf("// %s constructs a strongly-typed %s.\n", builderName, cloudEventStruct))
	sb.WriteString(fmt.Sprintf("func %s(data %s, source string, opts ...%s) %s {\n", builderName, payloadStruct, optionType, cloudEventStruct))
	sb.WriteString(fmt.Sprintf("\tevent := %s{\n", cloudEventStruct))
	sb.WriteString("\t\tSpecVersion:     \"1.0\",\n")
	sb.WriteString("\t\tID:              fmt.Sprintf(\"ce-%d\", time.Now().UnixNano()),\n")
	sb.WriteString("\t\tSource:          source,\n")
	sb.WriteString(fmt.Sprintf("\t\tType:            %q,\n", contract.Type))
	sb.WriteString("\t\tTime:            time.Now().UTC().Format(time.RFC3339),\n")
	sb.WriteString("\t\tDataContentType: \"application/json\",\n")
	sb.WriteString("\t\tData:            data,\n")
	sb.WriteString("\t}\n")
	sb.WriteString("\tfor _, opt := range opts {\n\t\topt(&event)\n\t}\n")
	sb.WriteString("\treturn event\n")
	sb.WriteString("}\n")

	return sb.String(), nil
}

func formatGoFieldName(name string) string {
	pascal := ToPascalCase(name)
	// Handle common initialisms
	replacements := map[string]string{
		"Id":    "ID",
		"Url":   "URL",
		"Uri":   "URI",
		"Http":  "HTTP",
		"Api":   "API",
		"Json":  "JSON",
		"Pii":   "PII",
		"Email": "Email",
	}

	for old, nw := range replacements {
		if strings.HasSuffix(pascal, old) {
			pascal = strings.TrimSuffix(pascal, old) + nw
		}
		if strings.HasPrefix(pascal, old) && len(pascal) == len(old) {
			pascal = nw
		}
	}
	return pascal
}

func mapToGoType(schemaType, itemType string) string {
	switch schemaType {
	case "string":
		return "string"
	case "number":
		return "float64"
	case "integer":
		return "int64"
	case "boolean":
		return "bool"
	case "array":
		if itemType != "" && itemType != "any" {
			return "[]" + mapToGoType(itemType, "")
		}
		return "[]any"
	case "object":
		return "map[string]any"
	default:
		return "any"
	}
}
